function write_music_bartlett_report(file,comparison)
%WRITE_MUSIC_BARTLETT_REPORT 记录实测单快拍MUSIC与Bartlett全组合比较。

fid=fopen(file,'w','n','UTF-8');
if fid<0,error('MusicComparison:ReportOpenFailed','无法写入%s。',file);end
cleanup=onCleanup(@()fclose(fid));
p=comparison.pipelinePair; d=comparison.doaPair; g=comparison.groupSummary;
fprintf(fid,'# 实测MUSIC与Bartlett全组合对照\n\n');
fprintf(fid,'生成时间：%s\n\n',char(datetime('now')));
fprintf(fid,['四分支共469种复响应方法，每种在Location1--4计算4个单阵位DOA，再运行' ...
    '6个两阵位、4个三阵位和1个四阵位组合。MUSIC与既有Bartlett各有%d条DOA和%d条定位链。' ...
    '两者使用同一份阵元复响应、%d个频点、相同有效掩码、阵列几何、方向网格和多射线定位器。\n\n'], ...
    height(d),height(p),numel(comparison.frequencyHz));
fprintf(fid,['## 证据边界\n\n每个位置及频点只有一个恢复后的阵元复响应向量。' ...
    '此处MUSIC令R=xx^H，以该秩一矩阵的正交补作为噪声子空间；' ...
    '各频点单独计算伪谱，再做宽带非相干平均。' ...
    '这是现有实测数据上的形式化单快拍MUSIC对照，未把相移状态或不同频点冒充同频多次独立快拍。' ...
    '在单个频点且导向向量模长固定时，MUSIC谱与Bartlett谱为单调变换，理论上峰位相同。' ...
    '宽带聚合非线性谱后峰位可能不同，但不能据此宣称多快拍MUSIC的分辨率或精度优势。\n\n']);
fprintf(fid,'## 全部方法的配对计数\n\n');
fprintf(fid,'| 项目 | Bartlett | MUSIC |\n|---|---:|---:|\n');
fprintf(fid,'| 单阵位DOA | %d | %d |\n',nnz(d.BartlettValid),nnz(d.MusicValid));
fprintf(fid,'| 数值有效定位 | %d | %d |\n',nnz(p.BartlettValid),nnz(p.MusicValid));
fprintf(fid,'| 数值有效但射线不全向前 | %d | %d |\n', ...
    nnz(p.BartlettValid & ~p.BartlettAllRaysForward), ...
    nnz(p.MusicValid & ~p.MusicAllRaysForward));
fprintf(fid,'\n## 四阵位结果：按复响应方法分组\n\n');
fprintf(fid,['| 分支 | 每阵位REV相移观测数 | 可配对四阵位结果 | ' ...
    'Bartlett误差中位数 | MUSIC误差中位数 | 同一子集误差差值中位数 | DOA方向差中位数 |\n']);
fprintf(fid,'|---|---:|---:|---:|---:|---:|---:|\n');
four=g(g.StationCount==4,:);
for index=1:height(four)
    fprintf(fid,'| %s | %s | %d | %.3f m | %.3f m | %+.3f m | %.3f° |\n', ...
        four.Branch{index},state_or_dash(four.StateCount(index)), ...
        four.PairedValidCount(index),four.BartlettMedianErrorM(index), ...
        four.MusicMedianErrorM(index), ...
        four.MedianMusicMinusBartlettErrorM(index), ...
        four.MedianDoaDifferenceDeg(index));
end
fprintf(fid,['\n完整逐DOA配对见`music_vs_bartlett_doa.csv`，逐定位链配对见' ...
    '`music_vs_bartlett_pipeline.csv`，2/3/4阵位分组统计见' ...
    '`music_vs_bartlett_group_summary.csv`。差值定义为MUSIC真值误差减Bartlett真值误差。\n']);
clear cleanup;
end

function value=state_or_dash(stateCount)
if isnan(stateCount),value='-';else,value=sprintf('%d',stateCount);end
end
